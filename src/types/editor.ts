export type EditorSourceRole = 'stem' | 'reference' | 'recording'

export type EditorSource = {
  id: string
  role: EditorSourceRole
  stemKey?: string | null
  path: string
  name: string
  duration: number
  sampleRate: number
  channels: number
  peaksPath?: string | null
  peaks?: number[]
  channelPeaks?: number[][]
  originKind?: 'task-result' | 'external' | 'legacy' | string
  originRoot?: string | null
  relativePath?: string | null
  missing?: boolean
}

export type EditorClip = {
  id: string
  assetId: string
  start: number
  offset: number
  duration: number
  volume: number
  fadeIn: number
  fadeOut: number
  muted: boolean
  locked: boolean
}

/** Persist unknown formats and opaque state references so projects remain recoverable. */
export type EditorPluginSlot = {
  id: string
  format: string
  pluginId: string
  name: string
  path: string
  bypassed: boolean
  skipLoad?: boolean
  state?: string
  [key: string]: unknown
}

export type EditorTrack = {
  id: string
  sourceId: string
  role: EditorSourceRole
  name: string
  /** Whether the displayed name is generated by Studio and may follow the UI locale. */
  autoName?: boolean
  color?: string | null
  volume: number
  pan: number
  muted: boolean
  solo: boolean
  fadeIn: number
  fadeOut: number
  /** Retained for older project versions; excluded from playback and export. */
  effects?: Record<string, unknown>
  pluginChain?: EditorPluginSlot[]
  type?: 'stem' | 'audio' | 'reference' | 'recording'
  clips?: EditorClip[]
}

export type EditorMasterLimiter = {
  enabled: boolean
  gainDb: number
  ceilingDb: number
  attackMs: number
  releaseMs: number
}

export type EditorSession = {
  id: string
  name: string
  sourceTaskId?: string
  sourceResultDir?: string
  masterVolume: number
  masterPan: number
  masterLimiter?: EditorMasterLimiter
  pluginChain?: EditorPluginSlot[]
  sources: EditorSource[]
  tracks: EditorTrack[]
  createdAt: number
  updatedAt: number
}

export type EditorProjectSummary = {
  id: string
  name: string
  sourceTaskId?: string
  sourceResultDir?: string
  createdAt: number
  updatedAt: number
  type: 'task' | 'blank'
}

export type EditorAsset = EditorSource
export type EditorProject = EditorSession & { assets?: EditorSource[] }
export type EditorAssetTreeNode = {
  key: string
  name: string
  path: string
  expanded?: boolean
  children: EditorAssetTreeNode[]
  assets: EditorAsset[]
}

export type EditorExportFormat = 'wav' | 'flac'
export type EditorExportSampleRate = 'auto' | 32000 | 44100 | 48000
export type EditorExportAudioParams = {
  wavBitDepth?: string
  flacBitDepth?: string
  sampleRate?: EditorExportSampleRate
  peakProtection?: boolean
}

export type EditorExportOptions = {
  format?: EditorExportFormat
  exportDir?: string
  fileName?: string
  audioParams?: EditorExportAudioParams
}
